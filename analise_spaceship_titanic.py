"""### 4.5 Análise de outliers

Aplicamos o critério do intervalo interquartil (IQR): são considerados outliers os valores abaixo de `Q1 - 1,5·IQR` ou acima de `Q3 + 1,5·IQR`.
"""

num_cols = ['Age'] + gastos + ['TotalSpend']

def conta_outliers(s):
    q1, q3 = s.quantile([0.25, 0.75])
    iqr = q3 - q1
    return int(((s < q1 - 1.5 * iqr) | (s > q3 + 1.5 * iqr)).sum())

out = pd.DataFrame({'Outliers (IQR)': [conta_outliers(df_clean[c]) for c in num_cols]}, index=num_cols)
out['% do total'] = (out['Outliers (IQR)'] / len(df_clean) * 100).round(2)
out['% de zeros'] = [(df_clean[c] == 0).mean() * 100 for c in num_cols]
out['% de zeros'] = out['% de zeros'].round(1)

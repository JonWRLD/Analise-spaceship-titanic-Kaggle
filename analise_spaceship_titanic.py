"""### 5.6 Principais achados da exploração

*(Os números de tabelas são exatos. Os lidos de gráficos de barras são aproximados e aparecem como "cerca de".)*

- **`CryoSleep` e `NoSpend`** são as variáveis mais associadas ao alvo (V de Cramér de 0,46 e 0,48). A taxa de transporte é de cerca de 0,82 para quem estava em criossono, contra cerca de 0,33 para quem não estava, e de cerca de 0,79 para quem não gastou nada, contra cerca de 0,30 para quem gastou. As duas variáveis são **redundantes** entre si (correlação de Spearman de 0,86), e `TotalSpend` também (−0,76 com `CryoSleep` e −0,89 com `NoSpend`).
- **Gastos:** associação negativa com o alvo. Pelo teste de Mann-Whitney, a correlação bisserial é de −0,47 para `TotalSpend`, −0,37 para `Spa`, −0,35 para `RoomService`, −0,34 para `VRDeck`, −0,22 para `ShoppingMall` e −0,18 para `FoodCourt`. A mediana de `TotalSpend` é 0 entre os transportados e 907 entre os não transportados.
- **`Deck` (V = 0,21) e `HomePlanet` (V = 0,20):** os decks B (cerca de 0,73) e C (cerca de 0,68) ficam bem acima da taxa geral, e D, E e F ficam abaixo (E, em torno de 0,36). O deck T tem pouquíssimos passageiros e intervalo de confiança muito largo, então não permite conclusão. Na origem, Europa (cerca de 0,66) fica acima da média, Marte (cerca de 0,52) perto dela e Terra (cerca de 0,43) abaixo.
- **`GroupSize` (V = 0,13), `Destination` (V = 0,11) e `Side` (V = 0,10):** associações pequenas, mas estatisticamente significativas. Quem viaja sozinho tem taxa de cerca de 0,45, enquanto grupos de 2 a 7 pessoas ficam entre cerca de 0,54 e 0,64 (o grupo de 8 tem poucos passageiros e intervalo largo). `55 Cancri e` tem taxa acima da média (cerca de 0,61), e o lado `S` fica um pouco acima do `P` (cerca de 0,55 contra 0,45).
- **`VIP`, `Age` e `CabinNum`:** associação muito fraca. `VIP` tem V de 0,04 (e poucos passageiros VIP, o que gera intervalo largo), e `Age` e `CabinNum` têm correlação bisserial de −0,08 e −0,05.
- **Correlações (Spearman):** entre os cinco tipos de gasto a correlação é moderada (de 0,18 a 0,50). `TotalSpend` tem correlação mais alta com cada um deles (de 0,51 a 0,67), o que é esperado, já que é a soma dos cinco. O que há de realmente forte é a redundância entre `CryoSleep`, `NoSpend` e `TotalSpend`, descrita acima.

## 6. Preparação para modelagem

**Seleção de variáveis.** Usamos as variáveis limpas e derivadas, agrupadas por tipo de tratamento.

**Pré-processamento (dentro de um `Pipeline`):**

- `Age`, `CabinNum`, `GroupSize`: padronização (`StandardScaler`).
- Gastos e `TotalSpend`: transformação `log(1 + x)` para reduzir a assimetria, seguida de padronização.
- `HomePlanet`, `Destination`, `Deck`, `Side`: codificação *one-hot*.
- `CryoSleep`, `VIP`, `NoSpend`: mantidas como estão (0/1).

Usar um `Pipeline` garante que as transformações sejam **ajustadas apenas nos dados de treino** em cada etapa, evitando vazamento de informação do teste.

**Divisão treino/teste:** 80% / 20%, estratificada pelo alvo, com semente fixa.
"""

feat_num_padrao = ['Age', 'CabinNum', 'GroupSize']
feat_num_gasto = gastos + ['TotalSpend']
feat_cat = ['HomePlanet', 'Destination', 'Deck', 'Side']
feat_bin = ['CryoSleep', 'VIP', 'NoSpend']

X = df_clean[feat_num_padrao + feat_num_gasto + feat_cat + feat_bin]
y = df_clean['Transported']

X_train, X_test, y_train, y_test = train_test_split(
    X, y, test_size=0.2, stratify=y, random_state=SEED)

print(f'Treino: {X_train.shape[0]} linhas | Teste: {X_test.shape[0]} linhas')
print(f'Taxa do alvo no treino: {y_train.mean():.3f} | no teste: {y_test.mean():.3f}')

preprocessador = ColumnTransformer([
    ('num', StandardScaler(), feat_num_padrao),
    ('gasto', Pipeline([
        ('log', FunctionTransformer(np.log1p, feature_names_out='one-to-one')),
        ('esc', StandardScaler())]), feat_num_gasto),
    ('cat', OneHotEncoder(handle_unknown='ignore'), feat_cat),
    ('bin', 'passthrough', feat_bin),
])

cv = StratifiedKFold(n_splits=5, shuffle=True, random_state=SEED)

"""## 7. Análise preditiva

Problema de **classificação binária**: prever `Transported` (0 ou 1).

Modelos:

1. **Baseline (classe majoritária):** referência mínima. Qualquer modelo útil precisa superá-lo.
2. **Regressão logística:** modelo linear, interpretável por meio dos coeficientes e *odds ratios*.
3. **Árvore de decisão:** modelo não linear, que captura interações entre variáveis e é interpretável por regras.

**Métricas:** acurácia, precisão, recall, F1 e AUC-ROC, além da matriz de confusão. Também usamos **validação cruzada estratificada (5 folds)** no conjunto de treino para estimar o desempenho de forma mais estável.

### 7.1 Ajuste da profundidade da árvore

Uma árvore sem limite de profundidade decora o treino (*overfitting*). Para escolher a profundidade, comparamos a acurácia média na validação cruzada (apenas com dados de treino) para profundidades de 1 a 15, fixando `min_samples_leaf = 20` para suavizar as folhas.
"""

profundidades = list(range(1, 16))
acc_treino, acc_cv = [], []

for d in profundidades:
    pipe = Pipeline([
        ('prep', preprocessador),
        ('clf', DecisionTreeClassifier(max_depth=d, min_samples_leaf=20, random_state=SEED))])
    res = cross_validate(pipe, X_train, y_train, cv=cv, scoring='accuracy', return_train_score=True)
    acc_treino.append(res['train_score'].mean())
    acc_cv.append(res['test_score'].mean())

melhor_prof = profundidades[int(np.argmax(acc_cv))]
print(f'Melhor profundidade (maior acurácia na validação cruzada): {melhor_prof} '
      f'(acurácia CV = {max(acc_cv):.4f})')

fig, ax = plt.subplots(figsize=(8, 4.5))
ax.plot(profundidades, acc_treino, marker='o', label='Treino')
ax.plot(profundidades, acc_cv, marker='o', label='Validação cruzada')
ax.axvline(melhor_prof, color='gray', linestyle='--', label=f'Escolhida: {melhor_prof}')
ax.set_xlabel('Profundidade máxima da árvore')
ax.set_ylabel('Acurácia')
ax.set_title('Escolha da profundidade da árvore')
ax.legend()
plt.tight_layout()
plt.show()

"""A acurácia de treino sobe continuamente com a profundidade (chega a cerca de 0,83), enquanto a de validação sobe até a profundidade de aproximadamente 5, se estabiliza em torno de 0,78 e oscila ou cai levemente nas profundidades maiores. A distância crescente entre as duas curvas indica *overfitting*.

A profundidade com maior acurácia na validação foi 8 (cerca de 0,781), mas a diferença para a profundidade 5 e as vizinhas é muito pequena, dentro da variação esperada entre *folds*. Mantemos a profundidade 8, escolhida pela regra objetiva de maior acurácia na validação cruzada. Uma árvore mais rasa (por exemplo, de profundidade 5) seria uma alternativa mais simples, com desempenho praticamente equivalente.

### 7.2 Treinamento e avaliação dos modelos
"""

modelos = {
    'Baseline (classe majoritária)': DummyClassifier(strategy='most_frequent'),
    'Regressão Logística': LogisticRegression(max_iter=1000, random_state=SEED),
    'Árvore de Decisão': DecisionTreeClassifier(max_depth=melhor_prof, min_samples_leaf=20, random_state=SEED),
}

pipelines, resultados = {}, []
for nome, clf in modelos.items():
    pipe = Pipeline([('prep', preprocessador), ('clf', clf)])
    cv_acc = cross_val_score(pipe, X_train, y_train, cv=cv, scoring='accuracy')
    pipe.fit(X_train, y_train)
    pred = pipe.predict(X_test)
    proba = pipe.predict_proba(X_test)[:, 1]
    pipelines[nome] = pipe
    resultados.append({
        'Modelo': nome,
        'Acurácia (CV)': cv_acc.mean(),
        'Acurácia (teste)': accuracy_score(y_test, pred),
        'Precisão': precision_score(y_test, pred, zero_division=0),
        'Recall': recall_score(y_test, pred),
        'F1': f1_score(y_test, pred),
        'AUC-ROC': roc_auc_score(y_test, proba),
    })

tab_res = pd.DataFrame(resultados).set_index('Modelo').round(4)
display(tab_res)

"""### 7.3 Matrizes de confusão e curvas ROC"""

fig, axes = plt.subplots(1, 3, figsize=(17, 4.8))

for ax, nome in zip(axes[:2], ['Regressão Logística', 'Árvore de Decisão']):
    pred = pipelines[nome].predict(X_test)
    ConfusionMatrixDisplay.from_predictions(
        y_test, pred, display_labels=['Não transp.', 'Transp.'], cmap='Blues', ax=ax, colorbar=False)
    ax.set_title(f'Matriz de confusão: {nome}')
    ax.grid(False)

for nome in ['Regressão Logística', 'Árvore de Decisão']:
    proba = pipelines[nome].predict_proba(X_test)[:, 1]
    fpr, tpr, _ = roc_curve(y_test, proba)
    axes[2].plot(fpr, tpr, label=f'{nome} (AUC = {roc_auc_score(y_test, proba):.3f})')
axes[2].plot([0, 1], [0, 1], 'k--', label='Aleatório')
axes[2].set_xlabel('Taxa de falsos positivos')
axes[2].set_ylabel('Taxa de verdadeiros positivos')
axes[2].set_title('Curvas ROC')
axes[2].legend()

plt.tight_layout()
plt.show()

"""### 7.4 Interpretação dos modelos

**Regressão logística:** o coeficiente de cada variável indica o efeito sobre o *log-odds* de ser transportado. O *odds ratio* (`exp(coeficiente)`) é mais fácil de interpretar: valores acima de 1 aumentam a chance de transporte, e abaixo de 1 reduzem. As variáveis numéricas estão padronizadas, então o odds ratio refere-se ao aumento de **1 desvio-padrão**.
"""

pipe_lr = pipelines['Regressão Logística']
nomes = [n.split('__')[-1] for n in pipe_lr.named_steps['prep'].get_feature_names_out()]
coefs = pd.Series(pipe_lr.named_steps['clf'].coef_[0], index=nomes)

top = coefs.reindex(coefs.abs().sort_values(ascending=False).head(14).index).sort_values()
fig, ax = plt.subplots(figsize=(8, 6))
cores = ['indianred' if v < 0 else 'seagreen' for v in top.values]
ax.barh(top.index, top.values, color=cores)
ax.axvline(0, color='black', linewidth=0.8)
ax.set_title('Regressão logística: 14 maiores coeficientes (em valor absoluto)')
ax.set_xlabel('Coeficiente (log-odds)')
plt.tight_layout()
plt.show()

tab_or = pd.DataFrame({'Coeficiente': top, 'Odds ratio': np.exp(top)}).sort_values('Odds ratio', ascending=False).round(3)
display(tab_or)

"""**Leitura dos resultados da regressão logística**

- **Aumentam a chance de transporte** (odds ratio acima de 1): `CryoSleep` (cerca de 2,56), `HomePlanet_Europa` (2,10), `Deck_C` (1,87), `FoodCourt` (1,59) e `Deck_B` (1,46).
- **Reduzem a chance** (odds ratio abaixo de 1): `Spa` (0,53), `TotalSpend` (0,54), `Deck_G` (0,56), `VRDeck` (0,57), `RoomService` (0,61), `HomePlanet_Earth` (0,61), `NoSpend` e `Deck_E` (0,69) e `VIP` (0,75).
- **Cuidado com a multicolinearidade.** `TotalSpend` é a soma dos gastos, `NoSpend` deriva dele e ambos estão fortemente ligados a `CryoSleep` (correlações de Spearman entre −0,89 e 0,86, seção 5.5). Nesse cenário, os coeficientes dessas variáveis **não devem ser lidos isoladamente**, porque cada um mede o efeito mantendo as demais constantes. Isso explica por que `NoSpend` tem coeficiente negativo, apesar de ter uma das associações marginais positivas mais fortes na EDA, e por que `FoodCourt` tem coeficiente positivo, apesar da associação marginal negativa.
- **`VIP`:** a associação marginal é muito fraca (V = 0,04), mas o odds ratio de cerca de 0,75 indica chance menor para passageiros VIP mesmo comparando passageiros com os mesmos gastos e demais características. Como há poucos passageiros VIP, a incerteza dessa estimativa é grande.

**Árvore de decisão:** a importância de cada variável mede o quanto ela contribuiu para reduzir a impureza nas divisões. Abaixo, também mostramos os primeiros níveis da árvore, que revelam as regras mais relevantes.
"""

pipe_ar = pipelines['Árvore de Decisão']
nomes_ar = [n.split('__')[-1] for n in pipe_ar.named_steps['prep'].get_feature_names_out()]
imp = pd.Series(pipe_ar.named_steps['clf'].feature_importances_, index=nomes_ar).sort_values(ascending=False).head(10)

fig, ax = plt.subplots(figsize=(8, 4.5))

df_clean[['PassengerId', 'Group', 'GroupSize', 'Cabin', 'Deck', 'CabinNum', 'Side']].head()

"""### 4.2 Tratamento de ausentes com regras de negócio

Antes de usar mediana ou moda, vale explorar relações lógicas entre as variáveis.

**Regra 1.** Passageiros em criossono ficam confinados à cabine e, portanto, não deveriam gastar nada nos serviços. Vamos verificar essa hipótese nos dados.
"""

em_cryo = df_clean['CryoSleep'] == 1
gasto_cryo = df_clean.loc[em_cryo, gastos].sum(axis=1)  # soma ignorando NaN
print(f'Passageiros em CryoSleep: {em_cryo.sum()}')
print(f'Desses, com algum gasto registrado: {(gasto_cryo > 0).sum()}')

"""A hipótese se confirma: **ninguém em criossono tem gasto positivo**. Logo, podemos aplicar duas regras:

- Se `CryoSleep = 1`, os gastos ausentes são **0**.
- Se `CryoSleep` está ausente mas o passageiro tem algum gasto positivo, ele **não** estava em criossono (`CryoSleep = 0`).

**Regra 2.** Passageiros do mesmo grupo costumam compartilhar o planeta de origem, então preenchemos `HomePlanet` ausente com o valor dos demais membros do grupo, quando houver.
"""

# Regra 1a: CryoSleep ausente + algum gasto > 0  ->  não estava em criossono
gasto_parcial = df_clean[gastos].sum(axis=1, skipna=True)
mask = df_clean['CryoSleep'].isna() & (gasto_parcial > 0)
print(f'CryoSleep inferido como 0 pela regra de gastos: {mask.sum()}')
df_clean.loc[mask, 'CryoSleep'] = 0

# Regra 1b: em criossono -> gastos ausentes viram 0
mask_cryo = df_clean['CryoSleep'] == 1
for c in gastos:
    df_clean.loc[mask_cryo, c] = df_clean.loc[mask_cryo, c].fillna(0)

# Regra 2: HomePlanet pela moda do grupo
planeta_grupo = (df_clean.dropna(subset=['HomePlanet'])
                 .groupby('Group')['HomePlanet']
                 .agg(lambda s: s.mode().iloc[0]))
antes = df_clean['HomePlanet'].isna().sum()
df_clean['HomePlanet'] = df_clean['HomePlanet'].fillna(df_clean['Group'].map(planeta_grupo))
print(f'HomePlanet ausente: {antes} -> {df_clean["HomePlanet"].isna().sum()}')

"""### 4.3 Imputação estatística dos ausentes restantes

Para o que sobrou, usamos medidas robustas:

- **Numéricas** (`Age`, `CabinNum` e gastos): **mediana**, que não é distorcida por valores extremos. Para os gastos, a mediana é 0, coerente com a maioria dos passageiros.
- **Categóricas e binárias**: **moda**.
"""

num_imput = ['Age', 'CabinNum'] + gastos
cat_imput = ['HomePlanet', 'Destination', 'Deck', 'Side', 'CryoSleep', 'VIP']

for c in num_imput:
    df_clean[c] = df_clean[c].fillna(df_clean[c].median())
for c in cat_imput:
    df_clean[c] = df_clean[c].fillna(df_clean[c].mode()[0])

# Binárias para inteiro
df_clean['CryoSleep'] = df_clean['CryoSleep'].astype(int)
df_clean['VIP'] = df_clean['VIP'].astype(int)

# Colunas que não serão mais usadas
df_clean = df_clean.drop(columns=['PassengerId', 'Name', 'Cabin', 'Group'])

print('Valores ausentes restantes:', df_clean.isna().sum().sum())

"""### 4.4 Variáveis derivadas

- `TotalSpend`: gasto total do passageiro nos cinco serviços.
- `NoSpend`: indica se o passageiro não gastou nada (1) ou gastou algo (0).

Essas variáveis resumem o comportamento de consumo e serão úteis tanto na exploração quanto na modelagem.
"""

